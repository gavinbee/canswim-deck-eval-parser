"""Tests for src/pdf_io.py.

Uses the synthetic fixture at tests/fixtures/form_field/session_1_evals.pdf
(generated by make_synthetic_fixture.py with seed=42). The fixture has 2
pages, 80 widgets per page, with 9 officials on page 1 and 2 officials on
page 2. All names are Faker-generated synthetic; no PII.
"""
from pathlib import Path

import pytest

from src import pdf_io


FIXTURE = (
    Path(__file__).parent / "fixtures" / "form_field" / "session_1_evals.pdf"
)


class TestOpenPdf:
    def test_missing_file_raises(self, tmp_path):
        with pytest.raises(FileNotFoundError):
            with pdf_io.open_pdf(tmp_path / "does-not-exist.pdf"):
                pass

    def test_opens_fixture(self):
        with pdf_io.open_pdf(FIXTURE) as doc:
            assert len(doc) == 2


class TestPageCount:
    def test_returns_two_for_fixture(self):
        assert pdf_io.page_count(FIXTURE) == 2


class TestHasFormFields:
    def test_true_for_fillable_pdf(self):
        assert pdf_io.has_form_fields(FIXTURE) is True

    def test_false_for_pdf_without_widgets(self, tmp_path):
        # Build a one-page PDF with no widgets so we exercise the negative
        # branch without committing another fixture.
        import fitz
        out = tmp_path / "plain.pdf"
        doc = fitz.open()
        doc.new_page()
        doc.save(out)
        doc.close()
        assert pdf_io.has_form_fields(out) is False


class TestReadWidgets:
    def test_page_0_has_80_widgets(self):
        widgets = pdf_io.read_widgets(FIXTURE, 0)
        assert len(widgets) == 80

    def test_page_0_meet_level_values(self):
        widgets = pdf_io.read_widgets(FIXTURE, 0)
        # Specific synthetic values produced by make_synthetic_fixture.py
        # with seed=42. Regenerate the fixture if the seed or Faker
        # version changes and these will need updating.
        assert widgets["Competition Name"] == "Clark Open 2026"
        assert widgets["Host Club"] == "TUF"
        assert widgets["COC"] == "Danielle Ford"
        assert widgets["Competition Coordinator"] == "Timothy Wong"

    def test_page_0_first_row(self):
        widgets = pdf_io.read_widgets(FIXTURE, 0)
        assert widgets["Name of OfficialRow1"] == "Allison Hill"
        assert widgets["ClubRow1"] == "HEX"
        assert widgets["PositionRow1"] == "Starter"

    def test_unfilled_widget_is_empty_string(self):
        widgets = pdf_io.read_widgets(FIXTURE, 0)
        # The blank "Successful initial" cells should be present as "".
        assert widgets["Successful initialRow1"] == ""
        # And the meet-level "Level" (cc_level) is also blank.
        assert widgets["Level"] == ""

    def test_page_index_out_of_range_raises(self):
        with pytest.raises(IndexError):
            pdf_io.read_widgets(FIXTURE, 99)

    def test_page_2_widgets_have_suffix_stripped(self):
        # The Swim Ontario form repeats widget names across pages; PyMuPDF
        # returns "Name of OfficialRow1 [226]" on page 2 to disambiguate.
        # read_widgets() must strip that so the template's bare names
        # still match.
        widgets = pdf_io.read_widgets(FIXTURE, 1)
        # The canonical (suffix-stripped) name must be present.
        assert "Name of OfficialRow1" in widgets
        # And the disambiguated form must NOT be present.
        assert not any("[" in name for name in widgets)

    def test_canonicalize_widget_name(self):
        # White-box test of the helper.
        assert (
            pdf_io._canonicalize_widget_name("Name of OfficialRow1 [226]")
            == "Name of OfficialRow1"
        )
        # Untouched if there's no suffix.
        assert (
            pdf_io._canonicalize_widget_name("Name of OfficialRow1")
            == "Name of OfficialRow1"
        )
        # Brackets that aren't a trailing duplicate marker are preserved.
        assert (
            pdf_io._canonicalize_widget_name("Some [weird] name")
            == "Some [weird] name"
        )


class TestRasterizePage:
    def test_returns_png_bytes(self):
        png = pdf_io.rasterize_page(FIXTURE, 0, dpi=72)
        # PNG magic bytes.
        assert png[:8] == b"\x89PNG\r\n\x1a\n"

    def test_higher_dpi_means_larger_png(self):
        small = pdf_io.rasterize_page(FIXTURE, 0, dpi=72)
        large = pdf_io.rasterize_page(FIXTURE, 0, dpi=150)
        # Higher DPI should yield more pixels and therefore more bytes
        # (PNG compression doesn't reverse that for a real document page).
        assert len(large) > len(small)

    def test_page_index_out_of_range_raises(self):
        with pytest.raises(IndexError):
            pdf_io.rasterize_page(FIXTURE, 99)


class TestPageDimensions:
    def test_returns_letter_landscape(self):
        # The Swim Ontario On-Deck Evaluation form is US Letter landscape:
        # 792 wide × 612 tall (PDF points = 1/72").
        w, h = pdf_io.page_dimensions(FIXTURE, 0)
        assert (w, h) == (792.0, 612.0)
        assert w > h  # explicit landscape sanity check
