class TestRowStripping:
    """Synthetic widget maps to cover the blank-row stripping logic
    without depending on a specific fixture."""

    def _make_widgets(self, rows: list[dict[str, str]]) -> dict[str, str]:
        """Build a Swim-Ontario-shaped widget dict for the given rows.

        Rows are sparse dicts keyed by canonical field name; everything
        else is blank.
        """
        widgets: dict[str, str] = {
            "Competition Name": "Test Meet",
            "Host Club": "TST",
            "COC": "A B",
            "Competition Coordinator": "C D",
            "Level": "",
            "Date  Session": "Sat, Jan 1, 2026 / Session 1",
            "Page": "1",
            "of": "1",
        }
        canonical_to_widget = {v: k for k, v in ONTARIO.widget_field_map.items()}
        for i in range(1, ONTARIO.rows_per_page + 1):
            row = rows[i - 1] if i - 1 < len(rows) else {}
            for canonical in s.ROW_FIELDS:
                widget_template = canonical_to_widget.get(canonical)
                if widget_template is None or "{i}" not in widget_template:
                    continue
                widget_name = widget_template.replace("{i}", str(i))
                widgets[widget_name] = row.get(canonical, "")
        return widgets

    def test_empty_page_yields_zero_rows(self):
        widgets = self._make_widgets([])
        page = form_extract.extract_page(widgets, ONTARIO, page_number=1)
        assert page.rows == []

    def test_row_with_only_one_filled_field_is_kept(self):
        widgets = self._make_widgets([{s.OFFICIAL_NAME: "Solo"}])
        page = form_extract.extract_page(widgets, ONTARIO, page_number=1)
        assert len(page.rows) == 1
        assert page.rows[0][s.OFFICIAL_NAME].value == "Solo"

    def test_whitespace_only_does_not_count_as_content(self):
        widgets = self._make_widgets([{s.OFFICIAL_NAME: "   "}])
        page = form_extract.extract_page(widgets, ONTARIO, page_number=1)
        assert page.rows == []

    def test_middle_blank_row_not_stripped(self):
        # Trailing blanks are stripped, but a blank between two filled
        # rows would be unusual — we don't attempt to preserve indices
        # since each row's place is implied by its order in the list.
        widgets = self._make_widgets(
            [
                {s.OFFICIAL_NAME: "First"},
                {},  # blank
                {s.OFFICIAL_NAME: "Third"},
            ]
        )
        page = form_extract.extract_page(widgets, ONTARIO, page_number=1)
        # We expect First then Third — the blank middle row is dropped.
        names = [r[s.OFFICIAL_NAME].value for r in page.rows]
        assert names == ["First", "Third"]


class TestTemplateAuthoringWarnings:
    """Warn (don't crash) when a template's widget_field_map points the
    wrong shape of widget at the wrong shape of field."""

    @dataclass(frozen=True)
    class FakeTemplate:
        id: str = "fake_v1"
        widget_field_map: dict | None = None
        rows_per_page: int = 9

    def test_non_row_widget_pointing_at_row_field_warns(self, caplog):
        # A widget without {i} but pointing at a per-row canonical key.
        # Use a minimal namespace duck-typed to Template.
        from src.templates.base import Template
        t = Template(
            id="fake_v1",
            display_name="Fake",
            field_names={},
            language="en",
            date_formats=[],
            vision_prompt_addendum="",
            widget_field_map={"BadWidget": s.OFFICIAL_NAME},
        )
        widgets = {"BadWidget": "value"}
        with caplog.at_level("WARNING"):
            page = form_extract.extract_page(widgets, t, page_number=1)
        assert page.rows == []
        assert page.meet == {}
        assert page.session == {}
        assert any("non-row widget" in r.message for r in caplog.records)

    def test_row_widget_pointing_at_meet_field_warns(self, caplog):
        from src.templates.base import Template
        t = Template(
            id="fake_v1",
            display_name="Fake",
            field_names={},
            language="en",
            date_formats=[],
            vision_prompt_addendum="",
            widget_field_map={"BadRowWidget{i}": s.COMPETITION_NAME},
        )
        widgets = {"BadRowWidget1": "value"}
        with caplog.at_level("WARNING"):
            page = form_extract.extract_page(widgets, t, page_number=1)
        assert page.rows == []
        assert any("per-row widget" in r.message for r in caplog.records)
