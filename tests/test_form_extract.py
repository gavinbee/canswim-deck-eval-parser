"""Tests for src/form_extract.py.

Uses the same synthetic fillable-PDF fixture as test_pdf_io (generated by
make_synthetic_fixture.py with seed=42; Faker-generated names, no PII).
Edge cases (partial pages, blank-row stripping, template-authoring bugs)
also use synthetic in-memory widget maps so they don't depend on a
particular fixture.
"""
from dataclasses import dataclass
from pathlib import Path

import pytest

from src import form_extract, schema as s
from src.templates import TEMPLATES


FIXTURE = (
    Path(__file__).parent / "fixtures" / "form_field" / "session_1_evals.pdf"
)
ONTARIO = TEMPLATES["swim_ontario_v1"]


class TestExtractPageFromFixture:
    def setup_method(self):
        from src import pdf_io
        self.widgets = pdf_io.read_widgets(FIXTURE, 0)
        self.page = form_extract.extract_page(self.widgets, ONTARIO, page_number=1)

    def test_page_number_set(self):
        assert self.page.page_number == 1

    def test_meet_fields_populated(self):
        meet = self.page.meet
        # Seed-42 synthetic values from make_synthetic_fixture.py.
        assert meet[s.COMPETITION_NAME].value == "Clark Open 2026"
        assert meet[s.HOST_CLUB].value == "TUF"
        assert meet[s.COC].value == "Danielle Ford"

    def test_session_fields_populated(self):
        session = self.page.session
        assert session[s.COMPETITION_COORDINATOR].value == "Timothy Wong"
        assert session[s.DATE_SESSION].value == "Fri, Jan 9, 2026 / Session 1"
        # cc_level is blank on this fixture — still emitted, just empty.
        assert session[s.CC_LEVEL].value == ""
        assert session[s.PAGE_NUMBER].value == "1"
        assert session[s.PAGE_OF].value == "2"

    def test_first_page_has_nine_rows(self):
        # 9 officials on the first page of the fixture.
        assert len(self.page.rows) == 9

    def test_first_row_fields(self):
        row = self.page.rows[0]
        assert row[s.OFFICIAL_NAME].value == "Allison Hill"
        assert row[s.CLUB].value == "HEX"
        assert row[s.POSITION].value == "Starter"

    def test_all_field_confidences_are_one(self):
        # Form-field path emits 1.0 across the board.
        for fv in self.page.meet.values():
            assert fv.confidence == 1.0
        for fv in self.page.session.values():
            assert fv.confidence == 1.0
        for row in self.page.rows:
            for fv in row.values():
                assert fv.confidence == 1.0


